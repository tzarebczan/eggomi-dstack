"""The stack and Eggomi agree on the channel bytes and the signed row bytes.

``vectors/eggomi-interop.json`` was generated by Eggomi's own code
(``interop/eggomi-interop.mjs`` driving ``channel.ts``, ``registry.ts`` and
``packages/noise``). ``InteropVectorTests`` recomputes every output with the
stack's Python and always runs.

``LiveEggomiTests`` runs Eggomi's TypeScript against the stack over real
sockets, and regenerates the vectors file to prove it is still Eggomi's
output. It needs ``node`` and ``CAH_EGGOMI_CHECKOUT`` (see
``scripts/eggomi-interop.sh``) and is skipped, by name, without them.
"""

